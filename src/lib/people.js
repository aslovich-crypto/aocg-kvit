// Автор записи: имя по идентификатору и обратный перевод имени в идентификатор.
//
// ⚠️ ВЫНЕСЕНО ИЗ `OtchetyPage` 04.09.2026 ПО ТРЕБОВАНИЮ ВЛАДЕЛЬЦА «готовое
// прежде своего». Механизм был написан для отчётов и работал верно; чекам
// нужен ровно он же. Вторая такая функция рядом разошлась бы с первой молча —
// ровно так у нас уже расходились копии скилла, пакета безопасности и правил
// дедупа. Здесь одно место на оба экрана.
//
// ⚠️ ПОЧЕМУ АВТОР ВООБЩЕ ПО `user_id`, А НЕ ПО ТЕКСТОВОЙ КОЛОНКЕ `employee`.
// Замер на проде 04.09.2026: в 88 чеках `employee` ПУСТА ВО ВСЕХ, а `user_id`
// заполнен во всех. Фронт при этом подставлял вместо пустоты имя владельца
// (`r.employee || "Алексей Шукалович"`), то есть выдавал чужой чек за его.
// Следствия было два: на «Сводке» все расходы складывались в одного человека,
// а фильтр «Сотрудник» по любому другому имени давал пустой список всегда —
// потому что сравнивалась подставленная строка, а не автор.

// Показывается там, где автор неизвестен: у записи нет `user_id` (старые
// строки) или человек уже не числится в организации.
//
// ⚠️ НЕ ПУСТОТА И НЕ ИМЯ ВЛАДЕЛЬЦА — решение владельца 04.09.2026. Пустое
// место читается как «автор есть, просто не поместился»; имя владельца —
// прямая ложь в документе. «Автор не указан» говорит ровно то, что есть.
export const АВТОР_НЕИЗВЕСТЕН = "Автор не указан";

/**
 * «Фамилия И.» — формат из макета отчётов, общий для обоих экранов.
 * Нет фамилии — имя; нет и его — почта; ничего нет — «Автор не указан».
 */
export function имяАвтора(uid, люди) {
  if (uid == null || !Array.isArray(люди)) return АВТОР_НЕИЗВЕСТЕН;
  const ч = люди.find((x) => x.id === uid);
  if (!ч) return АВТОР_НЕИЗВЕСТЕН;
  const фамилия = (ч.last_name || "").trim();
  const имя = (ч.first_name || "").trim();
  if (фамилия) return имя ? `${фамилия} ${имя[0]}.` : фамилия;
  return имя || ч.email || АВТОР_НЕИЗВЕСТЕН;
}

/**
 * Обратный перевод: выбранное в фильтре ИМЯ → идентификатор человека.
 *
 * ⚠️ ФИЛЬТР СРАВНИВАЕТ ИДЕНТИФИКАТОРЫ, А НЕ СТРОКИ, и это главное в правке.
 * Пока сравнивались строки, «показ» и «отбор» жили на разных полях: подпись
 * бралась из одного места, отбор из другого, и разойтись они могли молча.
 * Здесь имя — только то, что человек видит и выбирает; решение принимается
 * по `id`.
 */
export function идПоИмени(имя, люди) {
  if (!имя || !Array.isArray(люди)) return null;
  const ч = люди.find(
    (x) =>
      `${x.first_name || ""} ${x.last_name || ""}`.trim() === имя ||
      x.email === имя,
  );
  return ч ? ч.id : null;
}

/**
 * Полное имя для списка ВЫБОРА: «Имя Фамилия», иначе почта, иначе «—».
 *
 * ⚠️ ФОРМАТОВ ДВА, И ОБА НУЖНЫ — это решение, а не разнобой.
 * `имяАвтора` («Шукалович А.») — ПОДПИСЬ в строке и карточке, формат из
 * макета отчётов: там место узкое и человек уже знает, кого ищет.
 * `полноеИмя` («Алексей Шукалович») — ВЫБОР в списке: в чипе фильтра
 * «Шукалович А.» и «Шукалов А.» неразличимы, а полные имена — да.
 * Порядок «Имя Фамилия» здесь канонный (см. шапку «Профиля» в App.jsx:
 * «ИМЯ ВПЕРЕДИ ФАМИЛИИ — так в каноне»).
 *
 * ⚠️ ПАРА К `идПоИмени`, И РАЗОРВАТЬ ЕЁ НЕЛЬЗЯ. Чип фильтра рисуется этой
 * функцией и ЕЁ ЖЕ строка кладётся значением; наверху `идПоИмени` переводит
 * строку обратно в `id`, сверяя с `«Имя Фамилия»` или почтой. Меняется одна —
 * меняется вторая тем же движением, иначе отбор молча перестанет находить
 * людей (ровно это чинил коммит `3d17843` 04.09.2026).
 *
 * ⚠️ ЩЕЛЬ, КОТОРУЮ ЭТА ФУНКЦИЯ УНАСЛЕДОВАЛА И НЕ ЗАКРЫВАЕТ (08.09.2026):
 * у человека без имени, фамилии И почты она вернёт «—», а `идПоИмени` строки
 * «—» не знает и вернёт `null` — условие отбора не сработает, и фильтр
 * молча покажет ВСЕ чеки вместо чеков выбранного. Отбор, который вместо
 * сужения снимает себя, — класс «отказ выглядит как успех». На проде почта
 * есть у всех (уникальный индекс `uq_users_email_lower`), но колонка
 * NULLable, то есть случай возможен. Сведение копий эту щель НЕ закрыло:
 * она переехала сюда вместе с формулой. Чинить отдельным решением владельца.
 *
 * ⚠️ И ОТКУДА ЗДЕСЬ ВЗЯЛАСЬ КОПИЯ — ЭТО НАШ ЖЕ ХВОСТ, А НЕ ЧУЖОЙ.
 * Функция заведена 04.09.2026 коммитом `3d17843` как общее место для фильтра
 * и НЕ БЫЛА ПОДКЛЮЧЕНА: фильтр остался на локальной `empName` из `App.jsx`,
 * живущей с 21.05.2026. Четыре дня копия существовала намеренно написанной
 * и неиспользуемой. Класс — «сделали и не подключили» (T149), случай
 * ЧЕТВЁРТЫЙ и самый тихий: не граница репозиториев, а один файл рядом.
 * ⚠️ Ни один прибор его не ловит: сторож достижимости `reachable.py` смотрит
 * ТОЛЬКО python в `app/`, во фронте такого сторожа нет вовсе, а eslint видит
 * неиспользуемое внутри модуля, но не неиспользуемый ЭКСПОРТ.
 */
export function полноеИмя(ч) {
  return `${ч.first_name || ""} ${ч.last_name || ""}`.trim() || ч.email || "—";
}
