// ⚠️ МУТАЦИИ СТОРОЖА СУММЫ (правило T11: непроверенный сторож — неработающий).
//
// СВОД ПЕЧАТАЕТ ТРИ ЧИСЛА: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО (правило T77).
// Непоставленный мутант неотличим от проверенного — поэтому третье число
// печатается всегда, а ненулевое даёт красный итог.
//
// ⚠️ ГЛАВНАЯ ЗДЕСЬ — М1: обнуление суммы в ОБЩЕМ месте обязано покраснить ВСЕ
// пути, а не один. До сведения (T177) такая мутация красила ровно один шаг.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ФАЙЛЫ = {
  общее: path.join(КОРЕНЬ, "src/lib/receipt.js"),
  прил: path.join(КОРЕНЬ, "src/App.jsx"),
};

const МУТАНТЫ = [
  {
    имя: "М1 сумма обнулена в ОБЩЕМ месте",
    файл: "общее",
    было: "return { ...r, amount: Number(r.amount) };",
    стало: "return { ...r, amount: 0 };",
    ждём: /РАСХОЖДЕНИЙ [4-9]|РАСХОЖДЕНИЙ 1[0-9]/,
    почему: "красными обязаны стать ВСЕ шаги с суммами, а не один",
  },
  {
    имя: "М2 путь перестал звать общую функцию",
    файл: "прил",
    было: "setReceipts(каноничныеЧеки(data));",
    стало: "setReceipts(Array.isArray(data) ? data : []);",
    ждём: /вызовов общей функции 5|второго места приведения нет: своих/,
    почему: "статическая половина считает вызовы: их станет пять",
  },
  {
    имя: "М3 логика «заменить или в начало» снята",
    файл: "прил",
    было: "prev.some((x) => x.id === norm.id)",
    стало: "false",
    ждём: /пропала логика|«заменить или в начало»/,
    почему: "правило списка обязано остаться в handleAdd",
  },
  {
    имя: "М4 warning перестал вырезаться",
    файл: "прил",
    было: "const { warning, ...receipt } = await res.json();",
    стало:
      "const receipt = await res.json();\n      const warning = receipt.warning;",
    ждём: /перестало вырезаться поле warning|warning вырезается в addR/,
    почему: "поле ответа ручки осело бы на объекте в списке",
  },
];

const прогнать = () => {
  try {
    return execFileSync(
      "node",
      [path.join(КОРЕНЬ, "scripts/check-summa.mjs")],
      {
        cwd: КОРЕНЬ,
        encoding: "utf8",
        timeout: 600000,
      },
    );
  } catch (е) {
    return String(е.stdout || "") + String(е.stderr || "");
  }
};

console.log("\nМУТАЦИИ СТОРОЖА СУММЫ");
const исходники = Object.fromEntries(
  Object.entries(ФАЙЛЫ).map(([к, п]) => [к, readFileSync(п, "utf8")]),
);

const чисто = прогнать();
if (/РАСХОЖДЕНИЙ/.test(чисто)) {
  console.log("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций");
  process.exit(1);
}
console.log("  обратный ход: на нетронутом коде расхождений нет ✓\n");

let поставлено = 0;
let поймано = 0;
const непоставленные = [];
for (const м of МУТАНТЫ) {
  const путь = ФАЙЛЫ[м.файл];
  const текст = исходники[м.файл];
  if (!текст.includes(м.было)) {
    непоставленные.push(м.имя);
    console.log(`  ✗ НЕ ПОСТАВЛЕН  ${м.имя}: якоря в файле нет`);
    continue;
  }
  writeFileSync(путь, текст.replace(м.было, м.стало), "utf8");
  поставлено += 1;
  const вывод = прогнать();
  writeFileSync(путь, текст, "utf8");
  const есть = м.ждём.test(вывод);
  поймано += есть ? 1 : 0;
  console.log(
    `  ${есть ? "✓ поймана" : "✗ ПРОПУЩЕНА"}  ${м.имя} — ${м.почему}`,
  );
}

console.log(
  `\nПОСТАВЛЕНО ${поставлено} · ПОЙМАНО ${поймано} · НЕ ПОСТАВЛЕНО ${непоставленные.length}`,
);
for (const [к, п] of Object.entries(ФАЙЛЫ)) {
  if (readFileSync(п, "utf8") !== исходники[к]) {
    console.log(`  ⚠️ ФАЙЛ ${к} НЕ ВОССТАНОВЛЕН — этого быть не должно`);
    process.exit(1);
  }
}
console.log("исходные файлы не тронуты ✓");
process.exit(поймано === поставлено && !непоставленные.length ? 0 : 1);
