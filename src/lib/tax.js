// Флаги режима: уменьшают ли расходы налог и платит ли орг НДС.
//
// ⚠️ ЩЕЛЬ, НАЗВАННАЯ ВСЛУХ (T179). Ключи здесь сторож сверяет с набором, а
// ЗНАЧЕНИЯ — нет, и не может: на бэке «расходы уменьшают базу» и «плательщик
// НДС» не записаны кодом НИГДЕ. Они есть — прозой, в комментарии
// app/routers/organizations.py:25-28. Сверять не с чем, поэтому пока это
// решение фронта. Закрыть щель — значит сперва сделать ту прозу данными
// рядом с TAX_SYSTEMS; тогда флаги лягут на тот же словарь и своего
// механизма не потребуют.
export function regimeFlags(regime) {
  return {
    reducesExpenses: ["osno", "usn_dr", "eshn"].includes(regime),
    vatPayer: regime === "osno",
  };
}

/** НДС одного чека, в рублях.
 *
 * СУММИРУЕМ ВСЕ СТАВКИ ИЗ `vat_breakdown` БЕЗ СПИСКА — и это не стилистика,
 * а причина, по которой мы здесь. Раньше стояло `vat_20 + vat_10`, то есть
 * список из двух ставок в коде фронта. С 2026 года действует 22%, и блок
 * «Входящий НДС» показывал МЕНЬШЕ ТРЕТИ настоящей суммы: замер по проду
 * 10.08.2026 — показывал 1 385,62 ₽ при верных 4 702,11 ₽, занижение
 * 3 316,49 ₽ (70,5%). Цифру переносят в декларацию.
 * Любой список ставок здесь устареет на следующей их смене ровно так же,
 * поэтому его нет: берём всё, что в разбивке лежит.
 *
 * ЧТО В РАЗБИВКЕ. Её собирает бэкенд по тегу 1199 ФФД и кладёт ТОЛЬКО
 * ставки с фактическим налогом: 0% и «без НДС» не попадают, расчётные
 * (20/120, 10/110, 5/105, 7/107, 22/122) сведены к своей базовой ставке.
 * Значит фильтровать здесь нечего — сложить и всё.
 *
 * ФОТО-ЧЕКИ: РАЗБИВКИ НЕТ, И ЭТО НЕ НЕДОДЕЛКА. Она строится из кодов ставок
 * ФНС (`items[].nds`), а распознавание фото таких кодов не даёт — OCR видит
 * суммы, а не коды. НДС такого чека лежит в старых колонках `vat_20`/`vat_10`,
 * поэтому запасной путь — они.
 *
 * ⚠️ ЗДЕСЬ БЫЛА МОЯ ОШИБКА, И ОНА ПОУЧИТЕЛЬНА (T26). Сначала запасным путём
 * стояло поле `nds` — с убедительным комментарием «у фото-чеков бэкенд
 * заполняет одно общее поле». Объяснение верное, но ПРО ДРУГОЙ СЛОЙ: `nds`
 * существует только в ответе ручки распознавания (`POST /api/receipts/ocr/`),
 * которым заполняется форма добавления. В БАЗЕ такого поля нет вовсе, и
 * `GET /api/receipts` его не отдаёт — а читает эта функция именно сохранённые
 * чеки. То есть запасной путь был написан для поля, которого в этих данных
 * не бывает, и фото-чеки давали бы 0. На проде это молчало: все чеки с НДС
 * сегодня из ФНС.
 *
 * ПОРЯДОК ВАЖЕН: есть разбивка — берём ТОЛЬКО её. У чеков ФНС старые колонки
 * тоже заполнены, и сложение дало бы двойной счёт — ошибку той же природы,
 * что чиним, только в другую сторону.
 *
 * ДВА ИСТОЧНИКА, И ПОРЯДОК У НИХ ЖЁСТКИЙ:
 *   ① `vat_breakdown` — чеки ФНС, полная разбивка по тегу 1199;
 *   ② `vat_total` — фото-чеки: «НДС есть, ставка не распознана».
 * Складывать нельзя: заполнены бывают оба, и сумма дала бы двойной счёт —
 * ошибку той же природы, что чиним, только в другую сторону.
 *
 * ХВОСТ `vat_20 + vat_10` УБРАН вместе с колонками (NDS-CLEANUP ③, 10.08.2026).
 * Перед удалением замерено на проде: чеков, у которых НДС лежал ТОЛЬКО в этих
 * колонках, — ноль, поэтому хвост никого не держал. Сам дроп в `init_db`
 * повторяет этот замер В МОМЕНТ ДЕЙСТВИЯ и отменяет удаление, если находит
 * хоть один такой чек.
 */
export function receiptVat(r) {
  const bd = r?.vat_breakdown;
  if (bd && typeof bd === "object") {
    const сумма = Object.values(bd).reduce((a, v) => a + (Number(v) || 0), 0);
    if (сумма > 0) return сумма;
  }
  return Number(r?.vat_total) || 0;
}

// Делит чеки на «можно/нельзя учесть» по tax_kind категории и считает
// входящий НДС (см. receiptVat). catalog → карта category_id → tax_kind.
export function computeTaxAccounting(receipts, catalog) {
  const taxKindById = {};
  (catalog?.groups || []).forEach((g) =>
    (g.categories || []).forEach((c) => {
      taxKindById[c.id] = c.tax_kind;
    }),
  );
  let deductible = 0;
  let nonDeductible = 0;
  let vatSum = 0;
  let vatCount = 0;
  receipts.forEach((r) => {
    if (taxKindById[r.category_id] === NON_DEDUCTIBLE)
      nonDeductible += Number(r.amount);
    else deductible += Number(r.amount);
    const v = receiptVat(r);
    if (v > 0) {
      vatSum += v;
      vatCount += 1;
    }
  });
  return {
    deductible,
    nonDeductible,
    vatSum,
    vatCount,
    taxTotal: deductible + nonDeductible,
  };
}
