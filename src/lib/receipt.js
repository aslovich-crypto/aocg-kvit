/** Один чек к канонической форме. Сегодня правило одно — сумма числом. */
export function каноничныйЧек(r) {
  return { ...r, amount: Number(r.amount) };
}

/** Список чеков тем же правилом. Не массив — пустой список, а не поломка. */
export function каноничныеЧеки(xs) {
  return Array.isArray(xs) ? xs.map(каноничныйЧек) : [];
}
