#!/usr/bin/env node
// ⚠️ СТОРОЖ КОНТРАКТА: статусы отчёта и источники чека — одни и те же по обе
// стороны (T39, заход 1).
//
// ЗАЧЕМ, ЗАМЕРОМ 06.09.2026. Один и тот же смысл записан на двух языках —
// литералом в python и литералом в javascript, — и совпадать они обязаны, а
// держалось это на том, что кто-то помнит. Статусы отчёта живут в 4 местах
// фронта, источники чека в 3; сервер при этом решает по СВОЕМУ списку и
// отвергает чужое значение. Разойдутся — узнаем от бухгалтера, а не от
// прибора.
//
// ⚠️ КОПИЯ ПОРОЖДАЕТСЯ ИЗ КОДА БЭКЕНДА, А НЕ ИЗ ВТОРОГО СЛОВАРЯ. Источник
// статусов — `Literal` в модели `StatusIn` (reports.py), по нему сервер
// ОТВЕРГАЕТ запрос; источник каналов — кортеж `SOURCES` (receipts.py, T42).
// Завести рядом JSON значило бы создать второй источник того же смысла.
//
// ЧТО ПРОВЕРЯЕТСЯ:
//   ① копия src/lib/contract.js на месте, несёт штамп и разбирается;
//   ② ни один экран не знает статуса, которого нет в копии («знает лишнее»);
//   ③ все статусы копии где-то используются («не знает нужного» — набор,
//      про который забыли, молча выпадает из показа);
//   ④ то же для источников чека;
//   ⑤ штамп копии сходится с содержимым — подменили источник и не
//      пересчитали штамп, сторож обязан покраснеть.
//
// ⚠️ ГРАНИЦА. Сторож НЕ проверяет, что русские слова статусов совпадают с
// тем, что лежит в базе: в базе они хранятся текстом, и это вопрос миграции
// данных, а не словаря (решение владельца 06.09.2026).
//
// ЗАПУСК: node scripts/check-contract.mjs (входит в npm run lint).
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const КОПИЯ = path.join(КОРЕНЬ, "src/lib/contract.js");

const беды = [];
console.log("\nКОНТРАКТ БАЗА ↔ ЭКРАН (статусы отчёта, источники чека)");

let текст;
try {
  текст = readFileSync(КОПИЯ, "utf8");
} catch {
  console.log("  ✗ нет src/lib/contract.js — копия не сгенерирована");
  console.log(
    "      починка: ./venv/bin/python tools/gen_dictionaries.py в бэкенде",
  );
  process.exit(1);
}

const массив = (имя) => {
  const м = текст.match(new RegExp(`export const ${имя} = \\[(.*?)\\];`, "s"));
  return м ? [...м[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]) : null;
};
const СТАТУСЫ = массив("REPORT_STATUSES");
const ИСТОЧНИКИ = массив("RECEIPT_SOURCES");
const штамп = (текст.match(/ШТАМП-ИСТОЧНИКА sha256: ([0-9a-f]{64})/) || [])[1];
const умолчание = (текст.match(/DEFAULT_RECEIPT_SOURCE = "([^"]*)"/) || [])[1];

if (!СТАТУСЫ || !ИСТОЧНИКИ || !штамп || !умолчание) {
  console.log("  ✗ копия не разбирается: нет наборов или штампа");
  process.exit(1);
}
console.log(
  `  копия: статусов ${СТАТУСЫ.length} · источников ${
    ИСТОЧНИКИ.length
  } · штамп ${штамп.slice(0, 12)}…`,
);

// ⑤ штамп считается по тем же данным и в том же виде, что в генераторе:
// json.dumps(..., ensure_ascii=False, sort_keys=True). Расхождение здесь
// означает, что копию правили руками, а штамп остался прежним.
const данные = {
  default_source: умолчание,
  receipt_sources: ИСТОЧНИКИ,
  report_statuses: СТАТУСЫ,
};
const посчитан = createHash("sha256")
  .update(JSON.stringify(данные), "utf8")
  .digest("hex");
if (посчитан === штамп) {
  console.log("  ✓ штамп сходится с содержимым копии");
} else {
  беды.push("штамп копии не отвечает её содержимому — правили руками");
  console.log(
    `  ✗ ШТАМП НЕ СХОДИТСЯ: в файле ${штамп.slice(
      0,
      12,
    )}…, посчитан ${посчитан.slice(0, 12)}…`,
  );
}

// Обход исходников: ищем строковые литералы наборов вне самой копии.
const файлы = [];
(function обойти(каталог) {
  for (const имя of readdirSync(каталог)) {
    const п = path.join(каталог, имя);
    if (statSync(п).isDirectory()) обойти(п);
    else if (/\.jsx?$/.test(имя) && п !== КОПИЯ) файлы.push(п);
  }
})(path.join(КОРЕНЬ, "src"));
const исходники = файлы.map((п) => [п, readFileSync(п, "utf8")]);

const проверить = (имя, набор, шаблон) => {
  // «фронт знает лишнее»: литерал вида набора, которого в копии нет.
  const лишние = new Map();
  for (const [п, т] of исходники) {
    for (const м of т.matchAll(шаблон)) {
      // ⚠️ В шаблоне две альтернативы, и совпавшая может быть второй —
      // тогда м[1] равен undefined. Первая редакция сторожа сообщала
      // «экран знает „undefined"»: замер отвечал не про экран, а про себя.
      const з = м[1] ?? м[2];
      if (!набор.includes(з)) лишние.set(з, path.relative(КОРЕНЬ, п));
    }
  }
  if (лишние.size === 0) {
    console.log(`  ✓ ${имя}: лишних значений на экранах нет`);
  } else {
    for (const [з, где] of лишние)
      беды.push(`${имя}: экран знает «${з}» (${где}), в копии такого нет`);
    console.log(
      `  ✗ ${имя}: экран знает лишнее — ${[...лишние.keys()].join(", ")}`,
    );
  }
  // «фронт не знает нужного»: значение копии не встречается нигде.
  const забытые = набор.filter(
    (з) =>
      !исходники.some(([, т]) => т.includes(`"${з}"`) || т.includes(`'${з}'`)),
  );
  if (забытые.length === 0) {
    console.log(`  ✓ ${имя}: все значения копии используются`);
  } else {
    беды.push(`${имя}: на экранах не используются ${забытые.join(", ")}`);
    console.log(`  ✗ ${имя}: экран не знает — ${забытые.join(", ")}`);
  }
};

// Статусы ищем по русским словам целиком: они и есть значения.
проверить(
  "статусы отчёта",
  СТАТУСЫ,
  /"(Черновик|На проверке|Одобрен|Отклонён|Возвращён|В работе|Утверждён|Принят)"/g,
);
// Источники — по месту употребления: source: "…" и сравнения с ним.
проверить(
  "источники чека",
  ИСТОЧНИКИ,
  /source:\s*"([a-z_]+)"|source\s*===\s*"([a-z_]+)"/g,
);

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`     · ${б}`));
  console.log(
    "\n  Починка: правится ИСТОЧНИК в бэкенде (Literal StatusIn / SOURCES),\n" +
      "  затем ./venv/bin/python tools/gen_dictionaries.py — копия порождается.\n",
  );
  process.exit(1);
}
console.log("\n  ✓ статусы и источники совпадают по обе стороны\n");
process.exit(0);
