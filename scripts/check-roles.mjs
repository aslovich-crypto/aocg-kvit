#!/usr/bin/env node
// ⚠️ СТОРОЖ РОЛЕЙ: белый список S-24 против того, что знает экран (T39, заход 3).
//
// ЗАЧЕМ, ЗАМЕРОМ 08.09.2026. Роли перечислены на бэке ОДИН раз — кортежем
// `ROLES` в app/auth.py, он же белый список S-24, — и ещё раз, независимо,
// во фронте: массив `ROLES` в App.jsx с подписями и описаниями, плюс восемь
// гейтов, сравнивающих роль РАВЕНСТВОМ. Обратная проверка ДО этого сторожа:
// вписал в экранный список роль `manager`, которой в белом списке нет, и
// прогнал всё, что есть, — npm run lint зелёный, npm run build зелёный,
// gen_dictionaries.py --check зелёный, dict_stamp зелёный, 704 теста зелёные.
// Лишнюю роль не ловило НИЧТО.
//
// Цена промаха названа в самом источнике: гейты сравнивают роль равенством,
// поэтому роль вне белого списка молча даёт права РЯДОВОГО сотрудника —
// подпись есть, прав нет, и разбираться будут на живом человеке.
//
// ⚠️ СЛОВАРЬ СВЕРЯЕТ, А НЕ КОПИРУЕТ (решение владельца 06.09.2026). Второго
// источника ролей не заведено: src/lib/roles.js никто не импортирует, и так
// задумано. Подписи и описания остаются решением экрана; порождённый файл
// живёт ДЛЯ ЭТОГО СТОРОЖА, а не вместо App.jsx.
//
// ЧТО ПРОВЕРЯЕТСЯ:
//   ① копия src/lib/roles.js на месте, разбирается, несёт штамп;
//   ② штамп сходится с содержимым — копию правили руками;
//   ③ экранный список ROLES (App.jsx) покрывает набор ТОЧНО: ни лишней роли,
//      ни забытой (забытая молча выпала бы из выбора при заведении человека);
//   ④ ни один гейт не сравнивает роль со строкой вне набора — та самая
//      «Admin» с большой буквы, ради которой S-24 и заведён;
//   ⑤ второго списка ролей во фронте нет.
//
// ⚠️ ЧЕГО ЭТОТ СТОРОЖ НЕ ВИДИТ. Копию, ОТСТАВШУЮ ОТ БЭКЕНДА: штамп сходится
// со своим же содержимым, экран знает ровно то же — всё зелено. Это половина
// python (`gen_dictionaries.py --check`), она одна читает код бэкенда.
// Замерено на налогах 08.09 и повторено на ролях: JS стережёт
// «копия ↔ экран», python — «код ↔ копия», ни один не заменяет другого.
//
// ⚠️ `manager` В НАБОР НЕ ВХОДИТ НАМЕРЕННО. Роль РП из «Финансов» в Приме
// никто не понимает, прав ей не даёт ни один гейт (app/auth.py:102).
// Сторож на неё покраснеет — это верно, а не досадно: появиться она должна
// вместе с FIN-01, а не потому, что список показался неполным.
//
// ЗАПУСК: node scripts/check-roles.mjs (входит в npm run lint).
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { исходники, прочитатьНабор, сверитьКлючи } from "./lib-nabor.mjs";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const КОПИЯ = path.join(КОРЕНЬ, "src/lib/roles.js");
const ЭКРАН = path.join(КОРЕНЬ, "src/App.jsx");
const ПОЧИНКА =
  "\n  Починка: правится ИСТОЧНИК на бэке (ROLES в app/auth.py, S-24),\n" +
  "  затем ./venv/bin/python tools/gen_dictionaries.py — копия порождается.\n";

const беды = [];
console.log("\nРОЛИ (белый список S-24 ↔ экран)");

const { набор, штамп, посчитан, беда } = прочитатьНабор(КОПИЯ, "ROLES");
if (беда) {
  console.log(`  ✗ ${беда}`);
  console.log(ПОЧИНКА);
  process.exit(1);
}
console.log(`  копия: ${набор.length} роли · штамп ${штамп.slice(0, 12)}…`);

// ②
if (посчитан === штамп) {
  console.log("  ✓ штамп сходится с содержимым копии");
} else {
  беды.push("штамп копии не отвечает её содержимому — правили руками");
  console.log(
    `  ✗ ШТАМП НЕ СХОДИТСЯ: в файле ${штамп.slice(0, 12)}…, ` +
      `посчитан ${посчитан.slice(0, 12)}…`,
  );
}

// ③ экранный список. Целимся в СМЫСЛ — `id:` внутри массива ROLES, — а не
// в вёрстку: заход 2 споткнулся на том, что prettier переставил переносы.
const текстЭкрана = readFileSync(ЭКРАН, "utf8");
const блок = текстЭкрана.match(/const ROLES = \[[\s\S]*?\n\];/);
if (!блок) {
  беды.push("в App.jsx не найден массив ROLES");
  console.log("  ✗ экранный список ROLES не найден");
} else {
  const ид = [...блок[0].matchAll(/id:\s*"([^"]*)"/g)].map((x) => x[1]);
  const свои = сверитьКлючи("экранный список", ид, набор);
  беды.push(...свои);
  if (свои.length) свои.forEach((б) => console.log(`  ✗ ${б}`));
  else console.log(`  ✓ экранный список покрывает набор точно (${ид.length})`);
}

// ④ гейты. Ищем сравнение или запасное значение у переменной с именем role:
// `role === "…"`, `u.role !== "…"`, `me.role || "…"`. Точка перед `role`
// в класс [^A-Za-z_] входит, поэтому `u.role` тоже ловится.
const ГЕЙТ = /(?:^|[^A-Za-z_])role\s*(?:===|!==|\|\|)\s*"([^"]*)"/g;
const вне = new Map();
let гейтов = 0;
for (const [п, т] of исходники(КОРЕНЬ, ["src/lib/roles.js"])) {
  for (const м of т.matchAll(ГЕЙТ)) {
    гейтов += 1;
    if (!набор.includes(м[1])) вне.set(м[1], п);
  }
}
if (вне.size === 0) {
  console.log(`  ✓ все гейты сравнивают с ролями набора (сравнений ${гейтов})`);
} else {
  for (const [з, где] of вне) {
    беды.push(`гейт сравнивает роль с «${з}» (${где}) — вне белого списка`);
    console.log(`  ✗ гейт вне набора: «${з}» в ${где}`);
  }
}

// ⑤ второго списка нет. Признак списка — не сами имена ролей (они по всему
// коду), а связка `id: "<роль>"`, которой описывается пункт выбора.
const вторые = исходники(КОРЕНЬ, ["src/App.jsx", "src/lib/roles.js"]).filter(
  ([, т]) =>
    набор.filter((р) => new RegExp(`id:\\s*"${р}"`).test(т)).length >= 2,
);
if (вторые.length === 0) {
  console.log("  ✓ второго списка ролей нет");
} else {
  for (const [п] of вторые) {
    беды.push(`второй список ролей в ${п} — экранный живёт в App.jsx`);
    console.log(`  ✗ второй список ролей: ${п}`);
  }
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`     · ${б}`));
  console.log(ПОЧИНКА);
  process.exit(1);
}
console.log("\n  ✓ роли совпадают по обе стороны\n");
process.exit(0);
