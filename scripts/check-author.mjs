const беды = [];

// ── СТАТИЧЕСКАЯ ПОЛОВИНА, И ОНА ЗДЕСЬ ОБЯЗАТЕЛЬНА. Возврат локальной копии
// формата (`empName` в App.jsx) поведения НЕ МЕНЯЕТ — она была байт-в-байт
// равна `полноеИмя`. На экране такую мутацию поймать нечем: копия и общая
// функция дают одну строку. Ловится только чтением кода — тем же приёмом,
// что в стороже суммы (T177), и по той же причине.
const ЧИТАТЬ = (о) => readFileSync(path.join(КОРЕНЬ, о), "utf8");
const ПРИЛОЖЕНИЕ = ЧИТАТЬ("src/App.jsx");
console.log("  СТАТИЧЕСКАЯ ПОЛОВИНА");
{
  // Сборка имени вручную ВНУТРИ фильтра: `${first} ${last}` рядом с employees.
  // ⚠️ ПРОВЕРЯЕМ САМО МЕСТО, А НЕ ОТСУТСТВИЕ СЛОВА. Первая редакция искала
  // «const empName» и обратную косую перед шаблонной строкой — и пропустила
  // мутацию, которая собрала имя ТУТ ЖЕ, но иначе отформатированную. Признак
  // должен утверждать, ЧТО СТОИТ в чипе, а не чего в файле нет.
  const чип =
    /employees\.map\(\(u\) => \[полноеИмя\(u\), полноеИмя\(u\)\]\)/.test(
      ПРИЛОЖЕНИЕ,
    );
  if (!чип)
    беды.push("чип фильтра рисуется НЕ общей функцией — вернулась своя сборка");
  console.log(
    `  ${
      чип ? "✓" : "✗"
    } чип фильтра рисуется общей функцией полноеИмя (формат один)`,
  );
  const своя = /const empName\s*=/.test(ПРИЛОЖЕНИЕ);
  if (своя) беды.push("в App.jsx вернулась копия empName");
  console.log(`  ${своя ? "✗" : "✓"} копии empName в App.jsx нет`);
}
