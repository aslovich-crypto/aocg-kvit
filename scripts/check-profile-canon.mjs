// ⚠️ СТОРОЖ КАНОНА ЛИЧНОГО КАБИНЕТА. Смотрит на ОТРИСОВАННЫЙ ЭКРАН,
// а не на список в исходнике.
//
// ⚠️ ЗАЧЕМ ИМЕННО ТАК. Прежняя сверка читала массив ГРУППЫ_КАБИНЕТА
// регулярным выражением и печатала «расхождений 0». За два этапа она
// пропустила ЧЕТЫРЕ расхождения подряд, и все четыре нашёл владелец
// глазами либо агент снимком:
//   ① заголовок «Личные данные» дублировал имя группы в хабе
//   ② «Петров Иван» вместо канонного «Иван Петров»
//   ③ пункт «Категории» вёл на экран с именем «Общие»
//   ④ пункт «Интеграции» вёл на экран с именем «Сервисы»
// Ни одно из четырёх нельзя увидеть в списке — они живут в отрисовке.
//
// ⚠️ ОТДЕЛЬНОЙ ЦЕЛЬЮ, НЕ В `npm run lint`: нужен Chrome, и прогон идёт
// секунды. Но при отсутствии браузера проверка НЕ МОЛЧИТ — печатает
// «ПРОВЕРКА НЕ ВЫПОЛНЕНА» и краснеет (класс T87).
import { execFileSync, spawn } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ПРОБА = path.join(КОРЕНЬ, "scripts/probe");
const ВЫВОД = path.join(ПРОБА, "__dist");
const КАНОН = path.join(
  КОРЕНЬ,
  "design/handoff/templates/profile/Профиль.html",
);
// ⚠️ ПОРТ СЛУЧАЙНЫЙ НА КАЖДЫЙ ПРОГОН. С постоянным два прогона подряд
// дрались за него: предыдущий `vite preview` не успевал умереть,
// новый падал по --strictPort, и проверка краснела НЕ ПО ДЕЛУ.
// На прогоне мутаций это дало три ложных «не поймана».
const ПОРТ = 5300 + Math.floor(Math.random() * 600);

const БРАУЗЕРЫ = [
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
];

// ⚠️ ПЛОТНОСТЬ — ВОПРОС ЗАКРЫТ РЕШЕНИЕМ ВЛАДЕЛЬЦА 06.09.2026.
// В `design/handoff/preview/screen-profile.html` лежат ТРИ варианта плотности
// на сравнение, и выбор между ними не делался — вопрос висел с 29.08 в T107.
// Решение: КАНОН ПЛОТНОСТИ — ТО, ЧТО ОТРИСОВАНО СЕГОДНЯ. Довод владельца: за
// неделю экран сложился, этот сторож по нему зелен, владелец им пользуется;
// значит образец — работающий экран, а не один из трёх снимков.
//
// ⚠️ ЧТО ЭТО ЗНАЧИТ ДЛЯ ПРИБОРА: плотность он НЕ ПРОВЕРЯЕТ и проверять не
// должен. Три варианта отличаются отступами и высотой строки, а не составом —
// группы, пункты, подписи и имена экранов у них одни. Сторож сверяет СОСТАВ,
// и это его граница, а не пробел: закрепи он ещё и пиксели, любая правка
// воздуха краснела бы как расхождение с макетом.
//
// ⚠️ ИМЕНОВАННЫЕ ОТСТУПЛЕНИЯ ОТ КАНОНА — с причиной и номером строки.
// Правило проекта: расхождение с макетом это дефект, а не вкус. Значит
// ОСОЗНАННОЕ расхождение обязано быть объявлено здесь — иначе оно
// неотличимо от небрежности.
// ⚠️ И ОТВОД ПРОТУХАЕТ: если подпись вернулась к канонной, а отступление
// всё ещё объявлено — сторож КРАСНЕЕТ. Протухший отвод так же вреден,
// как молчащий пропуск (T92, именованный пропуск в sql_check).
const ОТСТУПЛЕНИЯ = {
  Аккаунт: {
    канон: "Имя, email, телефон",
    стало: "Контакты, роль, карты",
    почему: "«Мои карты» переехали сюда 29.08 — подпись описывала 3 вещи из 8",
    строка: "T113",
  },
};

const беды = [];
console.log("\nКАНОН ЛИЧНОГО КАБИНЕТА (по отрисованному экрану)");

const браузер = БРАУЗЕРЫ.find((п) => existsSync(п));
if (!браузер) {
  console.log(
    "  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не найден Chrome ни по одному из путей:",
  );
  БРАУЗЕРЫ.forEach((п) => console.log(`      ${п}`));
  console.log("    Экран рисует браузер — без него сверять нечего.");
  process.exit(1);
}
if (!existsSync(КАНОН)) {
  console.log(`  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: нет канона ${КАНОН}`);
  console.log("    Выгрузка ДС не распакована — сверять не с чем.");
  process.exit(1);
}

// ─── канон: группы, пункты, подписи ───────────────────────────────────
const канон = readFileSync(КАНОН, "utf8");
const группыКанона = [...канон.matchAll(/class="ghdr">([^<]+)</g)].map((м) =>
  м[1].trim(),
);
const пунктыКанона = [
  ...канон.matchAll(
    /class="rt">([^<]+)<\/span>\s*(?:<span class="rs">([^<]*)<\/span>)?/g,
  ),
].map((м) => ({ имя: м[1].trim(), подпись: (м[2] || "").trim() }));

// ─── проба: собрать, поднять, снять ───────────────────────────────────
try {
  // ⚠️ прямой путь к vite, а не npx: npx на холодную уходит в разрешение
  // пакета и вешает проверку на минуты. Таймаут обязателен — зависший
  // сторож это не «зелено», это «неизвестно».
  execFileSync(
    path.join(КОРЕНЬ, "node_modules/.bin/vite"),
    ["build", "--config", path.join(ПРОБА, "vite.config.mjs")],
    { cwd: КОРЕНЬ, stdio: "pipe", timeout: 120000 },
  );
} catch (е) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: проба не собралась");
  console.log(
    String(е.stdout || е.message)
      .split("\n")
      .slice(-6)
      .map((с) => "      " + с)
      .join("\n"),
  );
  process.exit(1);
}

// ⚠️ СТРАНИЦУ ОТДАЁТ `vite preview`, А НЕ САМОДЕЛЬНЫЙ СЕРВЕР. Свой
// http-сервер на node отвечал curl-у кодом 200, но безоконный Chrome
// на нём ВИС — причину не искал, взял то, что доказано работает.
// Замер важнее красоты: висящая проверка это не «зелено», это
// «неизвестно», и хуже красного.
// ⚠️ БЕЗ --user-data-dir. Замер: ВСЕ удачные прогоны шли без него,
// ВСЕ зависшие — с ним. Флаг ставился как средство от замка
// профиля, а оказался причиной зависания.
let замер = null;
let ошибка = "";

const сервер = spawn(
  path.join(КОРЕНЬ, "node_modules/.bin/vite"),
  [
    "preview",
    "--config",
    path.join(ПРОБА, "vite.config.mjs"),
    "--port",
    String(ПОРТ),
    "--strictPort",
  ],
  { cwd: КОРЕНЬ, stdio: "ignore" },
);

try {
  // ждём готовности порта, а не «сколько-нибудь секунд»
  let поднялся = false;
  for (let i = 0; i < 60 && !поднялся; i++) {
    await new Promise((г) => setTimeout(г, 250));
    try {
      const о = await fetch(`http://localhost:${ПОРТ}/`);
      поднялся = о.ok;
    } catch {
      /* ещё не поднялся */
    }
  }
  if (!поднялся) throw new Error("сервер пробы не поднялся за 15 с");

  // ⚠️ ЗАМЕР СНИМАЕТСЯ С ПОВТОРОМ, И ПОВТОРЯЕТСЯ ТОЛЬКО НЕСОСТОЯВШЕЕСЯ
  // ИЗМЕРЕНИЕ, НИКОГДА — РАСХОЖДЕНИЕ. Замер 31.08.2026: из восьми прогонов
  // один вернул DOM короче на 911 знаков — `#root` на месте, слова «Профиль»
  // нет, код возврата Chrome 0. То есть страница выгрузилась ДО того, как
  // отработал модуль: `--virtual-time-budget` истекает, пока настоящая
  // загрузка бандла ещё идёт. Сторож краснел каждый шестой раз впустую, а
  // сторож, которому не верят, не сторож. Пересняли — снялось; если не
  // снялось ни разу из трёх, красное остаётся, и это уже настоящая беда.
  const снять_разом = () =>
    new Promise((готово, споткнулись) => {
      const дитя = spawn(
        браузер,
        [
          "--headless",
          "--disable-gpu",
          "--virtual-time-budget=10000",
          "--window-size=430,3000",
          "--dump-dom",
          `http://localhost:${ПОРТ}/`,
        ],
        { stdio: ["ignore", "pipe", "ignore"] },
      );
      let вывод = "";
      const часы = setTimeout(() => {
        дитя.kill("SIGKILL");
        споткнулись(new Error("браузер не ответил за 90 с"));
      }, 90000);
      дитя.stdout.on("data", (к) => (вывод += к));
      дитя.on("error", (е) => {
        clearTimeout(часы);
        споткнулись(е);
      });
      дитя.on("close", () => {
        clearTimeout(часы);
        готово(вывод);
      });
    });

  let dom = "";
  let попыток = 0;
  for (; попыток < 3; попыток++) {
    dom = await снять_разом();
    if (/<div id="ЗАМЕР">[\s\S]*?\S[\s\S]*?<\/div>/.test(dom)) break;
  }
  const м = dom.match(/<div id="ЗАМЕР">([\s\S]*?)<\/div>/);
  if (м && м[1].trim()) {
    if (попыток > 0)
      console.log(`  ⚠️ замер снялся только с попытки ${попыток + 1} из 3`);
    замер = JSON.parse(
      м[1]
        .replace(/&quot;/g, '"')
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">"),
    );
  } else
    ошибка =
      `браузер не вернул замер за 3 попытки (DOM ${dom.length} знаков, ` +
      `#root ${dom.includes('id="root"') ? "есть" : "нет"}) — ` +
      `похоже, страница не отрисовалась, а не просто не успела`;
} catch (е) {
  ошибка = String(е.message).slice(0, 300);
} finally {
  сервер.kill("SIGKILL");
}

if (!замер) {
  console.log(`  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: ${ошибка}`);
  process.exit(1);
}

// ─── ① группы, пункты и подписи против канона ─────────────────────────
console.log(
  `  ГРУППЫ   канон ${группыКанона.length} · экран ${замер.группы.length}`,
);
if (группыКанона.join("|") !== замер.группы.join("|")) {
  беды.push("группы расходятся с каноном");
  console.log(
    `  ✗ ГРУППЫ РАСХОДЯТСЯ: канон [${группыКанона}] · экран [${замер.группы}]`,
  );
}
console.log(
  `  ПУНКТЫ   канон ${пунктыКанона.length} · экран ${замер.пункты.length}`,
);
let плохих = 0;
пунктыКанона.forEach((к) => {
  const э = замер.пункты.find((x) => x.имя === к.имя);
  if (!э) {
    плохих++;
    console.log(`  ✗ пункта «${к.имя}» на экране НЕТ`);
  } else if (э.подпись !== к.подпись) {
    const о = ОТСТУПЛЕНИЯ[к.имя];
    if (о && о.канон === к.подпись && о.стало === э.подпись) {
      console.log(
        `  ⚠️ ОТСТУПЛЕНИЕ «${к.имя}»: «${э.подпись}» вместо канонного «${к.подпись}»`,
      );
      console.log(`      причина: ${о.почему} · ${о.строка}`);
    } else {
      плохих++;
      console.log(
        `  ✗ «${к.имя}»: подпись «${э.подпись}» ≠ канон «${к.подпись}»`,
      );
    }
  } else if (ОТСТУПЛЕНИЯ[к.имя]) {
    плохих++;
    console.log(
      `  ✗ «${к.имя}»: отступление объявлено, а подпись КАНОННАЯ — отвод протух, снимите его`,
    );
  }
});
замер.пункты.forEach((э) => {
  if (!пунктыКанона.some((к) => к.имя === э.имя)) {
    плохих++;
    console.log(`  ✗ на экране лишний пункт «${э.имя}» — в каноне его нет`);
  }
});
if (плохих) беды.push(`пунктов расходится: ${плохих}`);
else console.log("  ✓ группы, пункты и подписи совпадают с каноном");

// ─── ② имя пункта против имени экрана, куда он ведёт ──────────────────
const мимо = замер.пункты.filter((п) => п.имя !== п.экран);
console.log(`  ПУНКТ → ЭКРАН   проверено ${замер.пункты.length}`);
if (мимо.length) {
  беды.push(`пункт ведёт на экран с другим именем: ${мимо.length}`);
  мимо.forEach((п) =>
    console.log(
      `  ✗ «${п.имя}» ведёт на экран «${п.экран}» — человек нажимает одно, попадает в другое`,
    ),
  );
} else console.log("  ✓ каждый пункт ведёт на экран со своим именем");

// ─── ③ заголовок внутри экрана дублирует имя экрана ───────────────────
const дубли = замер.экраны.filter((э) => э.заголовки.includes(э.экран));
console.log(`  ЗАГОЛОВКИ ВНУТРИ   проверено экранов ${замер.экраны.length}`);
if (дубли.length) {
  беды.push(`заголовок дублирует имя экрана: ${дубли.length}`);
  дубли.forEach((э) =>
    console.log(
      `  ✗ экран «${э.экран}» содержит заголовок «${э.экран}» — он уже назван в шапке`,
    ),
  );
} else console.log("  ✓ ни один экран не повторяет своё имя заголовком");

// ─── ④ порядок имени в карточке ───────────────────────────────────────
console.log(`  КАРТОЧКА   «${замер.имя}»`);
if (замер.имя !== "Иван Петров") {
  беды.push(`имя в карточке: «${замер.имя}» вместо «Иван Петров»`);
  console.log("  ✗ ИМЯ ВПЕРЕДИ ФАМИЛИИ — в каноне «Иван Петров»");
} else console.log("  ✓ имя впереди фамилии, как в каноне");

// ─── ⑤ первый блок экрана идёт БЕЗ заголовка ──────────────────────────
// ⚠️ Правило канона, измеренное на «Сводке»: шесть блоков, ПЯТЬ
// заголовков — первый без. Он и есть то, ради чего экран открыт.
// Правило вёрстки целиком — docs/RULES-FRONTEND.md.
const сверху = замер.экраны.filter((э) => э.первыйЗаголовком);
console.log(`  ПЕРВЫЙ БЛОК   проверено экранов ${замер.экраны.length}`);
if (сверху.length) {
  беды.push(`первый блок подписан: ${сверху.length}`);
  сверху.forEach((э) =>
    console.log(
      `  ✗ экран «${э.экран}»: первый блок начинается с заголовка — по канону он без него`,
    ),
  );
} else console.log("  ✓ ни один экран не начинается с заголовка");

// ─── ⑥ «Выйти» ровно в одном месте ────────────────────────────────────
// ⚠️ Выход — действие над всем приложением, а не над разделом. Дубль
// внутри «Аккаунта» был остатком отменённого макета ui_kits (T109).
console.log(`  «ВЫЙТИ»   найдено кнопок ${замер.выйти}`);
if (замер.выйти !== 1) {
  беды.push(`кнопок «Выйти»: ${замер.выйти} вместо одной`);
  console.log(
    `  ✗ «ВЫЙТИ» ${
      замер.выйти === 0
        ? "НЕ НАЙДЕНА ВОВСЕ"
        : "ВСТРЕЧАЕТСЯ " + замер.выйти + " РАЗ"
    } — должна быть ровно одна, в хабе`,
  );
} else console.log("  ✓ «Выйти» ровно одна, в хабе");

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  process.exit(1);
}
console.log("  ИТОГ: кабинет отрисовывается по канону");
