// ⚠️ СТОРОЖ СУММЫ НА ВСЕХ ПУТЯХ ПОКАЗА ЧЕКА (T177).
//
// ЗАЧЕМ, ЗАМЕРОМ 06–07.09.2026. Чек попадает на экран ШЕСТЬЮ путями, и каждый
// приводил сумму САМ. Мутация `amount: 0` в приёме списка НЕ ПОДЕЙСТВОВАЛА на
// только что добавленный чек: сквозной сторож идёт по ручному вводу, а мутация
// стояла в ветке, через которую тот сценарий не проходит ни разу.
//
// ⚠️ ТРЕТЬЯ ОСЬ КЛАССА, И ОНА ЦЕННЕЕ ПРАВКИ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ОНА
// РАЗОБРАНА (остальные файлы ссылаются сюда).
//
// Ось первая — ЧУЖОЙ ЭКРАН (T165): прибор смотрит туда, где механизм удобнее
// замерить, а не туда, где человек нажимает.
// Ось вторая — ЧУЖАЯ ЦЕЛЬ (T158): прибор прибит к адресу, с которого мы уехали.
// Ось третья — ЧУЖАЯ ВЕТКА КОДА (T177, 06.09.2026): экран верный, прибор
// верный, а мутация стоит в ветке, через которую сценарий пробы не проходит
// ни разу. Мутация обязана ставиться в ту ветку, через которую идёт СЦЕНАРИЙ,
// а не в ту, где правило записано «по смыслу».
//
// ⚠️ ОСЬ СУЗИЛАСЬ 07.09.2026 (UX-26): ЧУЖОЙ УЗЕЛ НА ТОМ ЖЕ ЭКРАНЕ. Правильный
// экран, правильный прибор, правильная ветка — и всё равно мимо: проба мерила
// строку СПИСКА вместо заголовка КАРТОЧКИ, а во второй раз — ту же строку
// вместо подписи под заголовком. Один раз это дало красное на верном коде,
// другой — ЗЕЛЁНОЕ на непроверенном месте.
// ЛЕЧЕНИЕ: искать узел по признаку, который его ОТЛИЧАЕТ, — кегль, роль,
// принадлежность к открытой карточке, — а не по порядку в DOM. `find` по
// тексту возвращает первое совпадение, и на экране с списком позади карточки
// первое совпадение почти всегда чужое.
//
// ЧТО ПРОВЕРЯЕТСЯ, ДВЕ ПОЛОВИНЫ — и границу между ними надо знать:
//   ЭКРАННАЯ. Один сценарий проходит по РАЗНЫМ путям, у каждого СВОЯ сумма:
//     450,00 — первая загрузка списка и перечитывание одного чека;
//     1 234,56 — добавление вручную; 777,77 — карточка дубля по 409.
//     Сумма читается ВИДИМЫМ текстом (T169), экран — «Чеки» (T165).
//   СТАТИЧЕСКАЯ. Приведение суммы обязано быть ОДНО и жить в
//     `src/lib/receipt.js`; второго `amount: Number(` в коде быть не должно.
//
// ⚠️ ПОЧЕМУ ВТОРАЯ ПОЛОВИНА НЕ МОЖЕТ БЫТЬ ЭКРАННОЙ — сказано прямо: у
// потребителей стоит 21 защитное `Number(*.amount)`, и путь, переставший
// звать общую функцию, на экране НЕ ПРОЯВИТСЯ — сумму починит потребитель.
// Пока перестраховка жива, «путь отвязали» ловится только чтением кода.
//
// ЗАПУСК: npm run summa (нужен Chrome; без него — «ПРОВЕРКА НЕ ВЫПОЛНЕНА»).
import { execFileSync, spawn } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ПРОБА = path.join(КОРЕНЬ, "scripts/probe-summa");
const ПОРТ = 5900 + Math.floor(Math.random() * 200);

const БРАУЗЕРЫ = [
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
];

const ОЖИДАЕМО = [
  ["① список — сумма первой загрузки", "450,00 на экране"],
  ["② карточка — сумма после перечитывания", "450,00 на экране"],
  ["③ карточка закрыта", "список на месте"],
  ["④ ввод чека открыт", "ввод открыт"],
  ["⑤ ручной ввод", "реквизиты"],
  ["⑥ форма чека", "форма"],
  ["⑦ новый чек со своей суммой", "1 234,56 на экране"],
  ["⑧ ввод дубля открыт", "ввод открыт"],
  ["⑨ реквизиты дубля", "реквизиты"],
  ["⑩ форма дубля", "форма"],
  ["⑪ дубль отклонён сервером", "плашка с «Открыть»"],
  ["⑫ карточка дубля — 777,77", "777,77 на экране"],
];

const беды = [];
console.log("\nСУММА НА ВСЕХ ПУТЯХ: одно правило, шесть путей (T177)");

// ── СТАТИЧЕСКАЯ ПОЛОВИНА. Идёт ПЕРВОЙ и без браузера: она отвечает на
// вопрос «все ли пути привязаны», а экранная — «верна ли цифра там, где
// человек смотрит». Ответы разные, и подменять один другим нельзя.
const ЧИТАТЬ = (о) => readFileSync(path.join(КОРЕНЬ, о), "utf8");
const ПРИЛОЖЕНИЕ = ЧИТАТЬ("src/App.jsx");
console.log("  СТАТИЧЕСКАЯ ПОЛОВИНА");

// ① приведение живёт в одном месте
const вторые = [...ПРИЛОЖЕНИЕ.matchAll(/amount:\s*Number\(/g)].length;
if (вторые) беды.push(`в App.jsx осталось ${вторые} своих приведений суммы`);
console.log(
  `  ${
    вторые ? "✗" : "✓"
  } второго места приведения нет: своих \`amount: Number(\` в App.jsx ${вторые}`,
);

// ② все шесть путей зовут общую функцию
const зовут = [...ПРИЛОЖЕНИЕ.matchAll(/каноничны(?:йЧек|еЧеки)\(/g)].length;
if (зовут < 6) беды.push(`вызовов общей функции ${зовут}, а путей шесть`);
console.log(
  `  ${
    зовут >= 6 ? "✓" : "✗"
  } путей привязано: вызовов общей функции ${зовут} (нужно ≥ 6)`,
);

// ③ логика списка осталась в handleAdd, а не уехала в общую функцию
const списочная = /prev\.some\(\(x\) => x\.id === norm\.id\)/.test(ПРИЛОЖЕНИЕ);
if (!списочная)
  беды.push("из handleAdd пропала логика «заменить или положить в начало»");
console.log(
  `  ${
    списочная ? "✓" : "✗"
  } «заменить или в начало» на месте — это правило списка, не чека`,
);

// ④ вырезание warning осталось в addR — это про форму ответа ручки
const варнинг = /const \{ warning, \.\.\.receipt \} = await res\.json\(\)/.test(
  ПРИЛОЖЕНИЕ,
);
if (!варнинг) беды.push("в addR перестало вырезаться поле warning");
console.log(
  `  ${
    варнинг ? "✓" : "✗"
  } warning вырезается в addR — это про ответ ручки, не про чек`,
);

console.log("  ЭКРАННАЯ ПОЛОВИНА");

const браузер = БРАУЗЕРЫ.find((п) => existsSync(п));
if (!браузер) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не найден Chrome — смотреть нечем");
  process.exit(1);
}

try {
  execFileSync(
    path.join(КОРЕНЬ, "node_modules/.bin/vite"),
    ["build", "--config", path.join(ПРОБА, "vite.config.mjs")],
    { cwd: КОРЕНЬ, stdio: "pipe", timeout: 180000 },
  );
} catch (е) {
  console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: проба не собралась");
  String(е.stdout || е.message)
    .split("\n")
    .slice(-6)
    .forEach((с) => console.log("      " + с));
  process.exit(1);
}

const сервер = spawn(
  path.join(КОРЕНЬ, "node_modules/.bin/vite"),
  [
    "preview",
    "--config",
    path.join(ПРОБА, "vite.config.mjs"),
    "--port",
    String(ПОРТ),
    "--strictPort",
  ],
  { cwd: КОРЕНЬ, stdio: "ignore" },
);

const снятьРазом = () =>
  new Promise((готово, споткнулись) => {
    const дитя = spawn(
      браузер,
      [
        "--headless",
        "--disable-gpu",
        "--virtual-time-budget=25000",
        "--window-size=430,1400",
        "--dump-dom",
        `http://localhost:${ПОРТ}/`,
      ],
      { stdio: ["ignore", "pipe", "ignore"] },
    );
    let вывод = "";
    const часы = setTimeout(() => {
      дитя.kill("SIGKILL");
      споткнулись(new Error("браузер не ответил за 120 с"));
    }, 120000);
    дитя.stdout.on("data", (к) => (вывод += к));
    дитя.on("error", (е) => {
      clearTimeout(часы);
      споткнулись(е);
    });
    дитя.on("close", () => {
      clearTimeout(часы);
      готово(вывод);
    });
  });

const разобрать = (dom) => {
  const м = dom.match(/<div id="ЗАМЕР">([\s\S]*?)<\/div>/);
  if (!м || !м[1].trim()) return null;
  try {
    return JSON.parse(
      м[1]
        .replace(/&quot;/g, '"')
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">"),
    );
  } catch {
    return null;
  }
};

try {
  let поднялся = false;
  for (let i = 0; i < 60 && !поднялся; i++) {
    await new Promise((г) => setTimeout(г, 250));
    try {
      поднялся = (await fetch(`http://localhost:${ПОРТ}/`)).ok;
    } catch {
      /* ещё не поднялся */
    }
  }
  if (!поднялся) throw new Error("сервер пробы не поднялся за 15 с");

  let замер = null;
  // Переснимаем только НЕСОСТОЯВШЕЕСЯ измерение; расхождение шага — результат.
  for (let п = 0; п < 3 && !замер; п++) {
    const р = разобрать(await снятьРазом());
    if (Array.isArray(р)) замер = р;
  }
  if (!замер) {
    console.log("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: замер не снялся за 3 попытки");
    сервер.kill("SIGKILL");
    process.exit(1);
  }
  ОЖИДАЕМО.forEach(([имя, ждём], i) => {
    const было = String(замер[i] ?? "")
      .split(": ")
      .slice(1)
      .join(": ");
    const ок = было === ждём;
    console.log(
      `  ${ок ? "✓" : "✗"} ${имя}: ${было || "НЕТ"}${
        ок ? "" : `  ← ждали «${ждём}»`
      }`,
    );
    if (!ок) беды.push(`${имя}: «${было || "НЕТ"}» вместо «${ждём}»`);
  });
} catch (е) {
  console.log(`  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: ${String(е.message).slice(0, 200)}`);
  сервер.kill("SIGKILL");
  process.exit(1);
} finally {
  сервер.kill("SIGKILL");
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`     · ${б}`));
  process.exit(1);
}
console.log(
  "\n  ✓ сумма верна на всех пройденных путях: загрузка, перечитывание,\n" +
    "    добавление, карточка дубля\n",
);
process.exit(0);
