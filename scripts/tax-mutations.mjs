#!/usr/bin/env node
// ПАРНЫЕ МУТАЦИИ К ДВУМ НАЛОГОВЫМ СТОРОЖАМ (T39, заход 2).
//
// Правило T11: сторож без мутации считается неработающим. Здесь каждая
// мутация ломает ровно одно, и проверяется НЕ ТОЛЬКО что кто-то покраснел,
// а ЧТО ПОКРАСНЕЛ ИМЕННО ТОТ — второй обязан остаться зелёным. Именно это
// и значит «два сторожа, ругаются независимо» (решение владельца 06.09.2026).
//
// ЗАПУСК: node scripts/tax-mutations.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ф = (о) => path.join(КОРЕНЬ, о);
const ОРГ = "scripts/check-tax-systems.mjs";
const ЧЕК = "scripts/check-fns-tax-codes.mjs";

function прогнать(сторож) {
  try {
    execFileSync("node", [ф(сторож)], { encoding: "utf8" });
    return "зелёный";
  } catch {
    return "красный";
  }
}

// Мутация = список правок [файл, было, стало]; применяем, мерим, откатываем.
//
// ⚠️ ЦЕЛЬ ЗАДАЁТСЯ РЕГУЛЯРКОЙ, А НЕ КУСКОМ ТЕКСТА С ПЕРЕНОСАМИ, И ЭТО
// КУПЛЕНО ОШИБКОЙ 08.09.2026. Первая редакция искала многострочный литерал
// массива — pre-commit прогнал prettier, тот сжал шестикодовый набор в одну
// строку (семикодовый не влез и остался в столбик), и М5 с М6 доложили
// «ЦЕЛЬ НЕ НАЙДЕНА»: 5 из 5 стало 3 из 5 без единой правки сторожей.
// Ровно об этом предупреждает шапка tools/gen_dictionaries.py — там то же
// случилось с M1 10.08.2026. Мутация обязана целиться в СМЫСЛ.
function мутация(имя, правки, ждём) {
  const снимки = правки.map(([о]) => [ф(о), readFileSync(ф(о), "utf8")]);
  try {
    for (const [о, было, стало] of правки) {
      const т = readFileSync(ф(о), "utf8");
      const есть = было instanceof RegExp ? было.test(т) : т.includes(было);
      if (!есть) throw new Error(`ЦЕЛЬ НЕ НАЙДЕНА в ${о}`);
      writeFileSync(ф(о), т.replace(было, стало));
    }
    const факт = { орг: прогнать(ОРГ), чек: прогнать(ЧЕК) };
    const сошлось = факт.орг === ждём.орг && факт.чек === ждём.чек;
    console.log(
      `${сошлось ? "  ✓" : "  ✗"} ${имя}\n` +
        `      ждали: режимы ${ждём.орг} · коды ${ждём.чек}\n` +
        `      вышло: режимы ${факт.орг} · коды ${факт.чек}`,
    );
    return сошлось;
  } catch (е) {
    console.log(`  ✗ ${имя}: ${е.message}`);
    return false;
  } finally {
    for (const [п, т] of снимки) writeFileSync(п, т);
  }
}

console.log("\nМУТАЦИИ НАЛОГОВЫХ СЛОВАРЕЙ\n");
console.log(`  исходно: режимы ${прогнать(ОРГ)} · коды ${прогнать(ЧЕК)}\n`);

const итоги = [
  // М3: экран знает режим, которого сервер не примет. Выбравший его человек
  // получил бы 422 при сохранении настроек.
  мутация(
    "М3 фронт знает лишний режим организации",
    [
      [
        "src/lib/tax.js",
        '  osno: "ОСНО",',
        '  osno: "ОСНО",\n  usn_6: "УСН 6%",',
      ],
    ],
    { орг: "красный", чек: "зелёный" },
  ),
  // М4: код из чека приходит, а подписи нет — карточка показала бы пустоту
  // на месте системы налогообложения продавца.
  мутация(
    "М4 фронт не знает нужного кода ФНС",
    [["src/components/ReceiptDetailModal.jsx", '  envd: "ЕНВД",\n', ""]],
    { орг: "зелёный", чек: "красный" },
  ),
  // М5: копию правили руками, штамп остался прежним. Без этой проверки
  // порождение вырождается в обычный файл, который «кто-то помнит».
  мутация(
    "М5 штамп не пересчитан при смене источника",
    [["src/lib/tax_systems.js", '"psn"', '"patent"']],
    { орг: "красный", чек: "зелёный" },
  ),
  // М6 ГЛАВНАЯ: наборы перепутаны местами — ровно то, чего опасался владелец,
  // когда потребовал отдельный файл на каждый набор. Краснеть обязаны ОБА:
  // если бы проверка была одна, общие четыре кода дали бы ей повод смолчать.
  мутация(
    "М6 словари перепутаны местами",
    [
      [
        "src/lib/tax_systems.js",
        /(export const TAX_SYSTEMS = )\[[\s\S]*?\];/,
        '$1["osno", "usn_income", "usn_income_minus_expense", "envd", "eshn", "psn", "npd"];',
      ],
      [
        "src/lib/fns_tax_codes.js",
        /(export const FNS_TAX_CODES = )\[[\s\S]*?\];/,
        '$1["eshn", "npd", "osno", "psn", "usn_d", "usn_dr"];',
      ],
    ],
    { орг: "красный", чек: "красный" },
  ),
  // М7: сведённый дубль вернулся. Без неё свод держался бы на том, что никто
  // не заведёт карту заново — то есть ровно на памяти, от которой лечимся.
  мутация(
    "М7 вторая карта режимов вернулась в OrganizationTab",
    [
      [
        "src/pages/OrganizationTab.jsx",
        'const TYPE_LABEL = { company: "Компания", person: "ИП" };',
        'const TYPE_LABEL = { company: "Компания", person: "ИП" };\n' +
          "const TAX_LABELS_2 = {\n  osno: 1,\n  usn_d: 2,\n  usn_dr: 3,\n};",
      ],
    ],
    { орг: "красный", чек: "зелёный" },
  ),
];

const поймано = итоги.filter(Boolean).length;
console.log(`\n  ПОЙМАНО ${поймано} ИЗ ${итоги.length}\n`);
process.exit(поймано === итоги.length ? 0 : 1);
