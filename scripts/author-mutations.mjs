// М6, потом М4. Мутант, который то ловится, то нет, ничего не говорит о себе —
// он говорит о том, что прибор иногда не отрабатывает вовсе (гонка за порт
// с соседней пробой). Непойманный мутант и неотработавший прибор давали
// ОДИН И ТОТ ЖЕ ответ, и второе выдавалось за первое.
// Теперь прибор без вердикта — отдельный исход: перезапуск, а при повторе
// честная строка «ПРИБОР НЕ ОТРАБОТАЛ», не смешиваемая с пропуском.
const ВЕРДИКТ = /РАСХОЖДЕНИЙ|✓ автор из user_id/;

const разОбойти = () => {
  try {
    return execFileSync(
      "node",
      [path.join(КОРЕНЬ, "scripts/check-author.mjs")],
      {
        cwd: КОРЕНЬ,
        encoding: "utf8",
        timeout: 900000,
      },
    );
  } catch (е) {
    return String(е.stdout || "") + String(е.stderr || "");
  }
};

const прогнать = () => {
  for (let i = 0; i < 3; i++) {
    const в = разОбойти();
    if (ВЕРДИКТ.test(в)) return в;
  }
  return null; // прибор не дал вердикта трижды
};

console.log("\nМУТАЦИИ СТОРОЖА АВТОРА");
