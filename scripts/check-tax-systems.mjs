#!/usr/bin/env node
// ⚠️ СТОРОЖ №1 ИЗ ДВУХ: РЕЖИМЫ ОРГАНИЗАЦИИ (T39, заход 2).
//
// ЗАЧЕМ, ЗАМЕРОМ 06.09.2026. Список режимов записан руками в трёх местах:
// `TAX_SYSTEMS` на бэке (organizations.py) — по нему сервер ОТВЕРГАЕТ PATCH,
// и две одинаковые карты подписей во фронте (src/lib/tax.js и
// src/pages/OrganizationTab.jsx). Две фронтовые были СИМВОЛ В СИМВОЛ одна и
// та же, каждая со своим комментарием «зеркало бэка» — то есть обе знали,
// что они зеркало, и ни одна не знала про другую.
//
// ⚠️ ПОЧЕМУ СТОРОЖА ДВА, А НЕ ОДИН НА ОБА НАЛОГОВЫХ НАБОРА. Решение владельца
// 06.09.2026: «разделы однажды перепутают, и ошибка будет молчаливой».
// Коды режимов организации и коды СНО из чека ПЕРЕСЕКАЮТСЯ, но не совпадают
// (osno, eshn, psn, npd есть в обоих; usn_d/usn_dr только здесь; envd и
// usn_income только в чеке). Сведённая проверка приняла бы один набор за
// другой на общих четырёх кодах. Здесь наборы ругаются порознь.
//
// ЧТО ПРОВЕРЯЕТСЯ:
//   ① копия src/lib/tax_systems.js на месте, разбирается, несёт штамп;
//   ② штамп сходится с содержимым — копию правили руками;
//   ③ подписи TAX_LABELS (src/lib/tax.js) покрывают набор ТОЧНО: ни лишнего
//      режима, ни забытого (забытый молча выпал бы из выпадающего списка);
//   ④ второй карты подписей во фронте нет — та самая сведённая копия;
//   ⑤ regimeFlags не знает режима вне набора.
//
// ⚠️ ЧЕГО ЭТОТ СТОРОЖ НЕ ВИДИТ, ЗАМЕРОМ 08.09.2026. Копия, ОТСТАВШАЯ ОТ
// БЭКЕНДА, для него исправна: добавил в `TAX_SYSTEMS` седьмой код `ausn` и
// не перегенерировал — оба JS-сторожа ЗЕЛЁНЫЕ, потому что штамп сходится со
// своим же содержимым, а экран знает ровно то же, что копия. Красной стала
// только python-половина (`gen_dictionaries.py --check`): она одна читает
// код бэкенда. Отсюда правило: JS-сторож стережёт «копия ↔ экран»,
// python — «код ↔ копия», и ни один не заменяет другого.
//
// ⚠️ ГРАНИЦА, НАЗВАННАЯ ВСЛУХ (T179). Сторож сверяет КЛЮЧИ regimeFlags, но не
// их ЗНАЧЕНИЯ: «уменьшают ли расходы налог» и «плательщик ли НДС» на бэке
// не записано НИГДЕ КОДОМ — только прозой в комментарии organizations.py:25.
// Сверять не с чем; пока источника нет, значения остаются решением фронта.
//
// ЗАПУСК: node scripts/check-tax-systems.mjs (входит в npm run lint).
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  ключиКарты,
  исходники,
  прочитатьНабор,
  сверитьКлючи,
} from "./lib-nabor.mjs";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const КОПИЯ = path.join(КОРЕНЬ, "src/lib/tax_systems.js");
const ПОДПИСИ = path.join(КОРЕНЬ, "src/lib/tax.js");
const ЧУЖАЯ = path.join(КОРЕНЬ, "src/lib/fns_tax_codes.js");
const ПОЧИНКА =
  "\n  Починка: правится ИСТОЧНИК на бэке (TAX_SYSTEMS в organizations.py),\n" +
  "  затем ./venv/bin/python tools/gen_dictionaries.py — копия порождается.\n";

const беды = [];
console.log("\nНАЛОГОВЫЕ РЕЖИМЫ ОРГАНИЗАЦИИ (бэк ↔ экран)");

const { набор, штамп, посчитан, беда } = прочитатьНабор(КОПИЯ, "TAX_SYSTEMS");
if (беда) {
  console.log(`  ✗ ${беда}`);
  console.log(ПОЧИНКА);
  process.exit(1);
}
console.log(`  копия: ${набор.length} режимов · штамп ${штамп.slice(0, 12)}…`);

// ② штамп
if (посчитан === штамп) {
  console.log("  ✓ штамп сходится с содержимым копии");
} else {
  беды.push("штамп копии не отвечает её содержимому — правили руками");
  console.log(
    `  ✗ ШТАМП НЕ СХОДИТСЯ: в файле ${штамп.slice(0, 12)}…, ` +
      `посчитан ${посчитан.slice(0, 12)}…`,
  );
}

// ③ подписи покрывают набор точно
const текстПодписей = readFileSync(ПОДПИСИ, "utf8");
const ключи = ключиКарты(текстПодписей, "TAX_LABELS");
if (!ключи) {
  беды.push("в src/lib/tax.js нет карты TAX_LABELS");
  console.log("  ✗ карта подписей TAX_LABELS не найдена");
} else {
  const свои = сверитьКлючи("подписи", ключи, набор);
  беды.push(...свои);
  if (свои.length) свои.forEach((б) => console.log(`  ✗ ${б}`));
  else console.log(`  ✓ подписи покрывают набор точно (${ключи.length})`);
}

// ④ второй карты нет. Отличаем именно ЭТОТ набор от кодов чека: общие четыре
// кода (osno, eshn, psn, npd) есть и там, и там, поэтому ищем по РАЗЛИЧАЮЩИМ.
const чужой = прочитатьНабор(ЧУЖАЯ, "FNS_TAX_CODES").набор || [];
const различающие = набор.filter((к) => !чужой.includes(к));
const вторые = исходники(КОРЕНЬ, [
  "src/lib/tax.js",
  "src/lib/tax_systems.js",
]).filter(
  ([, т]) =>
    различающие.filter((к) => new RegExp(`^\\s*${к}\\s*:`, "m").test(т))
      .length >= 2,
);
if (вторые.length === 0) {
  console.log(
    `  ✓ второй карты режимов нет (различали по ${различающие.join(", ")})`,
  );
} else {
  for (const [п] of вторые) {
    беды.push(`вторая карта режимов в ${п} — подписи живут в src/lib/tax.js`);
    console.log(`  ✗ вторая карта режимов: ${п}`);
  }
}

// ⑤ regimeFlags знает только режимы набора
const тело = (текстПодписей.match(/function regimeFlags[\s\S]*?\n\}/) || [
  "",
])[0];
const вФлагах = [
  ...new Set([...тело.matchAll(/"([a-z_]+)"/g)].map((x) => x[1])),
];
const лишниеФлаги = вФлагах.filter((к) => !набор.includes(к));
if (лишниеФлаги.length === 0) {
  console.log(`  ✓ regimeFlags знает только режимы набора (${вФлагах.length})`);
} else {
  беды.push(`regimeFlags знает вне набора — ${лишниеФлаги.join(", ")}`);
  console.log(`  ✗ regimeFlags знает вне набора: ${лишниеФлаги.join(", ")}`);
}

if (беды.length) {
  console.log(`\n  ⚠️ РАСХОЖДЕНИЙ ${беды.length}`);
  беды.forEach((б) => console.log(`     · ${б}`));
  console.log(ПОЧИНКА);
  process.exit(1);
}
console.log("\n  ✓ режимы организации совпадают по обе стороны\n");
process.exit(0);
