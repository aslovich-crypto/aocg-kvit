// пустым, и экран говорил «данных нет». Человек читает это как факт и идёт
// делать лишнюю работу: заводит документ, который на самом деле есть, звонит
// администратору про «пропавшие права», выписывает второе приглашение.
// Класс всплывал шесть раз за два дня, каждый раз случайно.
//
// ⚠️ ПОЧЕМУ ОТДЕЛЬНЫЙ КОМПОНЕНТ, А НЕ ТЕКСТ ПО МЕСТУ. Текст уже был написан
// дважды — на экране входа по ссылке и в списке приглашений. Третья копия
// разошлась бы с первыми молча: у нас так уже расходились словари, правила
// и копия скилла. Одно место — один текст.
//
// ⚠️ КНОПКА ПОВТОРА ОБЯЗАТЕЛЬНА. Разница между «пусто» и «не загрузилось» не
// в словах, а в том, что человек делает дальше: в первом случае заводит
// запись, во втором — пробует ещё раз. Отказ без способа повторить оставляет
// его ровно там же, где молчание.
import { theme, FONT } from "../lib/theme";

export default function LoadFailure({ что, onRetry, компактно = false }) {
  return (
    <div
      role="status"
      style={{
        fontSize: 12,
        color: theme.fg2,
        fontFamily: FONT,
        lineHeight: 1.5,
        padding: компактно ? "4px 2px" : "10px 12px",
        background: компактно ? "none" : theme.surfaceSunk,
        borderRadius: компактно ? 0 : 10,
        border: компактно ? "none" : `1px solid ${theme.border}`,
      }}
    >
      {`Не удалось загрузить ${что} — сервер не ответил. Это не значит, что ${
        компактно ? "их нет" : "данных нет"
      }.`}{" "}
      {onRetry && (
        <button
          type="button"
          onClick={onRetry}
          style={{
            border: "none",
            background: "none",
            padding: 0,
            color: theme.cherry,
            fontFamily: FONT,
            fontSize: 12,
            fontWeight: 600,
            cursor: "pointer",
          }}
        >
          Загрузить ещё раз
        </button>
      )}
    </div>
  );
}
