// ПАРНЫЕ МУТАЦИИ К СТОРОЖАМ ПОРОЖДЁННЫХ СЛОВАРЕЙ (T39, заходы 2 и 3).
//
// Правило T11: сторож без мутации считается неработающим. Здесь каждая
// мутация ломает ровно одно, и проверяется НЕ ТОЛЬКО что кто-то покраснел,
// а ЧТО ПОКРАСНЕЛ ИМЕННО ТОТ — соседние обязаны остаться зелёными. Именно
// это и значит «сторожа ругаются независимо» (решение владельца 06.09.2026).
//
// ⚠️ ОДИН НАБОР МУТАЦИЙ НА ВСЕ ТРИ СЛОВАРЯ, А НЕ ФАЙЛ НА СЛОВАРЬ. Проверка
// «сосед смолчал» требует гнать ВСЕХ сторожей на каждой мутации; раздели
// их по файлам — и каждый набор проверял бы только себя, то есть ровно ту
// половину, ради которой всё затевалось, никто бы и не мерил.
//
// ЗАПУСК: node scripts/slovar-mutations.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ф = (о) => path.join(КОРЕНЬ, о);
const СТОРОЖА = {
  режимы: "scripts/check-tax-systems.mjs",
  коды: "scripts/check-fns-tax-codes.mjs",
  роли: "scripts/check-roles.mjs",
};

function прогнать(сторож) {
  try {
    execFileSync("node", [ф(сторож)], { encoding: "utf8" });
    return "зелёный";
  } catch {
    return "красный";
  }
}

// Мутация = список правок [файл, было, стало]; применяем, мерим, откатываем.
//
// ⚠️ ЦЕЛЬ ЗАДАЁТСЯ РЕГУЛЯРКОЙ, А НЕ КУСКОМ ТЕКСТА С ПЕРЕНОСАМИ, И ЭТО
// КУПЛЕНО ОШИБКОЙ 08.09.2026. Первая редакция искала многострочный литерал
// массива — pre-commit прогнал prettier, тот сжал шестикодовый набор в одну
// строку (семикодовый не влез и остался в столбик), и М5 с М6 доложили
// «ЦЕЛЬ НЕ НАЙДЕНА»: 5 из 5 стало 3 из 5 без единой правки сторожей.
// Ровно об этом предупреждает шапка tools/gen_dictionaries.py — там то же
// случилось с M1 10.08.2026. Мутация обязана целиться в СМЫСЛ.
function мутация(имя, правки, ждём) {
  const снимки = правки.map(([о]) => [ф(о), readFileSync(ф(о), "utf8")]);
  try {
    for (const [о, было, стало] of правки) {
      const т = readFileSync(ф(о), "utf8");
      const есть = было instanceof RegExp ? было.test(т) : т.includes(было);
      if (!есть) throw new Error(`ЦЕЛЬ НЕ НАЙДЕНА в ${о}`);
      writeFileSync(ф(о), т.replace(было, стало));
    }
    // Молчание соседа — часть замера, поэтому не названный в `ждём` сторож
    // обязан быть ЗЕЛЁНЫМ, а не «каким получится».
    const полный = {
      режимы: "зелёный",
      коды: "зелёный",
      роли: "зелёный",
      ...ждём,
    };
    const факт = {};
    for (const [имяН, путь] of Object.entries(СТОРОЖА))
      факт[имяН] = прогнать(путь);
    const сошлось = Object.keys(полный).every((к) => факт[к] === полный[к]);
    const строкой = (о) =>
      Object.entries(о)
        .map(([к, з]) => `${к} ${з}`)
        .join(" · ");
    console.log(
      `${сошлось ? "  ✓" : "  ✗"} ${имя}\n` +
        `      ждали: ${строкой(полный)}\n` +
        `      вышло: ${строкой(факт)}`,
    );
    return сошлось;
  } catch (е) {
    console.log(`  ✗ ${имя}: ${е.message}`);
    return false;
  } finally {
    for (const [п, т] of снимки) writeFileSync(п, т);
  }
}

console.log("\nМУТАЦИИ ПОРОЖДЁННЫХ СЛОВАРЕЙ\n");
console.log(
  "  исходно: " +
    Object.entries(СТОРОЖА)
      .map(([и, п]) => `${и} ${прогнать(п)}`)
      .join(" · ") +
    "\n",
);

